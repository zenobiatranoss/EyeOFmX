#!/usr/bin/env bash
# Build the static download site from files produced by packaging/build.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SITE="$ROOT/site"
DIST="$ROOT/dist"
DOWNLOADS="$SITE/downloads"
VERSION="${VERSION:-1.0.1}"

mkdir -p "$DOWNLOADS"
find "$DOWNLOADS" -mindepth 1 -maxdepth 1 -type f -delete

entries=()

add_entry() {
  local id="$1" label="$2" arch="$3" dir="$4" pattern="$5" template="$6"
  local file name base size sha install json

  file="$(find "$dir" -maxdepth 1 -type f -name "$pattern" -print -quit 2>/dev/null || true)"
  if [[ -z "$file" ]]; then
    echo "site: skipping $id (no $pattern in $dir)"
    return
  fi

  name="$(basename "$file")"
  base="${name%.tar.gz}"
  install="${template//@FILE@/$name}"
  install="${install//@BASE@/$base}"
  cp -f "$file" "$DOWNLOADS/$name"
  size="$(stat -c%s "$file" 2>/dev/null || wc -c < "$file")"
  sha="$(sha256sum "$file" | awk '{print $1}')"

  json=$(printf '    {"id":"%s","label":"%s","arch":"%s","file":"%s","size":%s,"sha256":"%s","install":"%s"}' \
    "$id" "$label" "$arch" "$name" "$size" "$sha" "$install")
  entries+=("$json")
}

fedora_dir="$DIST/fedora"
[[ -d "$fedora_dir" ]] || fedora_dir="$DIST/rpm"
opensuse_dir="$DIST/opensuse"
[[ -d "$opensuse_dir" ]] || opensuse_dir="$DIST/rpm"

add_entry debian   "Debian / Ubuntu"             "amd64"   "$DIST/debian"   '*.deb'          'sudo apt install ./@FILE@'
add_entry fedora   "Fedora / RHEL / Rocky / Alma" "x86_64" "$fedora_dir"    '*.rpm'          'sudo dnf install ./@FILE@'
add_entry opensuse "openSUSE"                    "x86_64" "$opensuse_dir"  '*.rpm'          'sudo zypper install ./@FILE@'
add_entry arch     "Arch / Manjaro"              "x86_64" "$DIST/arch"     '*.pkg.tar.zst'  'sudo pacman -U ./@FILE@'
add_entry alpine   "Alpine / postmarketOS"       "x86_64" "$DIST/alpine"   '*.apk'          'sudo apk add --allow-untrusted ./@FILE@'
add_entry generic  "Any Linux with GTK 3"        "x86_64" "$DIST/generic"  '*.tar.gz'       'tar -xzf @FILE@ && cd @BASE@ && sudo install -m755 eyeofmx /usr/local/bin/'

json_list=""
for entry in "${entries[@]}"; do
  if [[ -n "$json_list" ]]; then
    json_list+=$',\n'
  fi
  json_list+="$entry"
done

cat > "$SITE/data.js" <<EOF
// Generated by site/generate.sh — do not edit by hand.
window.EYEOF_MANIFEST = {
  "version": "$VERSION",
  "generated": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "files": [
$json_list
  ]
};
EOF

cp -f "$ROOT/LICENSE" "$SITE/LICENSE.txt"
cp -f "$ROOT/assets/icons/64x64/apps/eyeofmx.png" "$SITE/favicon.png"
cp -f "$ROOT/back.png" "$SITE/back.png"
cp -f "$ROOT/back2.png" "$SITE/back2.png"
cp -f "$ROOT/back3.png" "$SITE/back3.png"
cp -f "$ROOT/og-image.jpg" "$SITE/og-image.jpg"
touch "$SITE/.nojekyll"
echo "Site data written to $SITE/data.js (${#entries[@]} download entries)"
